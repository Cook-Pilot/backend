--      롤 삼계탕            "마늘 15(3개)" 인데 다른 줄은 "마늘 10g(2개)" → g
--   2. 출처 데이터셋 전체 단위 토큰 분포가 g 11,690 / 개 495 / 장 117 / ml 93 로
--      그램이 사실상 표기 관례다.
--   3. 값의 크기가 그램일 때만 성립한다(후추 0.01, 흰후추 0.02, 소금 0.38, 물 200~500).
--      1인분 열량과도 맞는다 — 가자미쑥국 123.4kcal, 호두떡볶이 383.1kcal.
--
