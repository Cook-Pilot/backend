-- 단위를 'g' 로 판정한 근거:
--   1. 같은 원문 안에서 형제 재료가 g 를 달고 있는 레시피가 6개다. 예)
--      감자를 곁들인 야채스튜 "양파 15, 청피망 15g, 가지 10g, ..."  → 양파도 g
