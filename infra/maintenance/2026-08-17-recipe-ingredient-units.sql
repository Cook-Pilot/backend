DO $$
DECLARE
  recipe_count    INT;
  backfill_count  INT;
  missing_rows    INT;
  amount_drift    INT;
  already_united  INT;
  outstanding     INT;
BEGIN
  SELECT count(*) INTO backfill_count FROM ingredient_unit_backfill;
  IF backfill_count <> 210 THEN
    RAISE EXCEPTION '백필 목록이 210행이어야 하는데 %행이다', backfill_count;
  END IF;

  -- 감사 대상 스냅샷 확인. 중복 정리 이후의 운영 레시피 수.
  SELECT count(*) INTO recipe_count FROM recipes;
  IF recipe_count <> 1150 THEN
    RAISE EXCEPTION '감사 스냅샷은 레시피 1150개인데 %개가 있다', recipe_count;
  END IF;

  -- 대상 행이 사라졌는가(레시피 삭제·재임포트).
  SELECT count(*) INTO missing_rows
  FROM ingredient_unit_backfill b
  WHERE NOT EXISTS (SELECT 1 FROM recipe_ingredients ri WHERE ri.id = b.id);
  IF missing_rows <> 0 THEN
    RAISE EXCEPTION '백필 대상 %행이 recipe_ingredients 에 없다', missing_rows;
  END IF;

  -- 수량이 감사 시점과 달라졌는가. 달라졌다면 단위 판정 근거도 다시 봐야 한다.
  SELECT count(*) INTO amount_drift
  FROM ingredient_unit_backfill b
  JOIN recipe_ingredients ri ON ri.id = b.id
  WHERE ri.amount IS DISTINCT FROM b.expected_amount;
  IF amount_drift <> 0 THEN
    RAISE EXCEPTION '%행의 amount 가 감사 시점과 다르다', amount_drift;
  END IF;

  -- 누군가 이미 단위를 채웠는가. 그렇다면 덮어쓰지 않고 멈춘다.
  SELECT count(*) INTO already_united
  FROM ingredient_unit_backfill b
  JOIN recipe_ingredients ri ON ri.id = b.id
  WHERE ri.unit IS NOT NULL;
  IF already_united <> 0 THEN
    RAISE EXCEPTION '%행에 이미 unit 이 채워져 있다. 스크립트를 다시 검토할 것', already_united;
  END IF;

  -- 감사 이후 목록 밖에 같은 결손이 새로 생겼는가. 있으면 이 스크립트로는 부족하다.
  SELECT count(*) INTO outstanding
  FROM recipe_ingredients ri
  WHERE ri.unit IS NULL
    AND ri.amount IS NOT NULL
    AND NOT EXISTS (SELECT 1 FROM ingredient_unit_backfill b WHERE b.id = ri.id);
  IF outstanding <> 0 THEN
    RAISE EXCEPTION '백필 목록 밖에 unit 결손이 %행 더 있다. 재감사 필요', outstanding;
  END IF;
END $$;

UPDATE recipe_ingredients ri
SET unit = b.unit
FROM ingredient_unit_backfill b
WHERE ri.id = b.id;

